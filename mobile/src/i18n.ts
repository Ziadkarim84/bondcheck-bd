// Every user-facing string, in Bangla and English.
export type Lang = 'bn' | 'en';

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
export const toBnDigits = (s: string | number) => String(s).replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
export const toLatinDigits = (s: string) => s.replace(/[০-৯]/g, (d) => String(BN_DIGITS.indexOf(d)));

/** Numbers in the user's language (bond numbers always stay Latin, as printed on results). */
export const num = (lang: Lang, n: number | string) => (lang === 'bn' ? toBnDigits(n) : String(n));
export const taka = (lang: Lang, n: number) => '৳' + num(lang, n.toLocaleString('en-IN'));

const MONTHS = {
  bn: ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'],
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
};
export function formatDate(lang: Lang, iso: string, short = false) {
  const [y, m, d] = iso.slice(0, 10).split('-').map(Number);
  const month = MONTHS[lang][m - 1];
  return `${num(lang, d)} ${short ? month.slice(0, lang === 'bn' ? 10 : 3) : month} ${num(lang, y)}`;
}
export const ordinalDraw = (lang: Lang, n: number) => (lang === 'bn' ? `${toBnDigits(n)}তম` : `${n}th`);
export const rankLabel = (lang: Lang, r: number) =>
  lang === 'bn' ? ['', '১ম', '২য়', '৩য়', '৪র্থ', '৫ম'][r] + ' পুরস্কার' : ['', '1st', '2nd', '3rd', '4th', '5th'][r] + ' prize';

